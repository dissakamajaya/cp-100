// Regenerates reference.h from the simulator's dsp.js (copied here as dsp.mjs).
// node gen_reference.mjs > reference.h
import { period } from './dsp.mjs';

const kOutputTrim = 0.5;  // firmware src/audio.h
const cases = [
  { name: 'pad1', frequencyHz: 128.5, levelPct: 35, wave: 'sine', foldPct: 0, harmonics: 'odd' },
  { name: 'pad2', frequencyHz: 196, levelPct: 35, wave: 'triangle', foldPct: 18, harmonics: 'odd' },
  { name: 'pad3', frequencyHz: 256, levelPct: 30, wave: 'sawtooth', foldPct: 32, harmonics: 'both' },
  { name: 'pad4', frequencyHz: 384, levelPct: 40, wave: 'sine', foldPct: 58, harmonics: 'both' },
  { name: 'console', frequencyHz: 220, levelPct: 30, wave: 'triangle', foldPct: 40, harmonics: 'both' },
  { name: 'persist', frequencyHz: 333.3, levelPct: 44, wave: 'sawtooth', foldPct: 12, harmonics: 'even' },
];
const N = 4096, K = 8;
const out = ['// Generated by gen_reference.mjs from simulator/dist/dsp.js period(); do not edit.',
  '// Harmonic amplitudes (1.0 = full scale) of one ideal period, times kOutputTrim.',
  'struct HarmonicRef { const char* name; float hz; int level; const char* wave; int fold; const char* harmonics; double rms; double amp[8]; };',
  'static const HarmonicRef kHarmonicRefs[] = {'];
for (const c of cases) {
  const x = period(c, N);
  let s = 0; for (const v of x) s += v * v;
  const amp = [];
  for (let k = 1; k <= K; k++) {
    let re = 0, im = 0;
    for (let i = 0; i < N; i++) { re += x[i] * Math.cos(2 * Math.PI * k * i / N); im -= x[i] * Math.sin(2 * Math.PI * k * i / N); }
    amp.push(2 * Math.hypot(re, im) / N * kOutputTrim);
  }
  out.push(`  {"${c.name}", ${c.frequencyHz.toFixed(1)}f, ${c.levelPct}, "${c.wave}", ${c.foldPct}, "${c.harmonics}", ${(Math.sqrt(s / N) * kOutputTrim).toPrecision(8)}, {${amp.map(a => a.toExponential(8)).join(', ')}}},`);
}
out.push('};');
console.log(out.join('\n'));
