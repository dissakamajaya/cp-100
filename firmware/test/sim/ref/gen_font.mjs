// Regenerates font.h from the simulator's app.js (copied here as app.js):
// the 5x7 matrix font and, for every text the CP-100 shows, the exact 32x8
// picture that app.js drawMatrix() paints. drawMatrix() itself is extracted
// and run against a fake canvas, so the centring is the simulator's own code,
// not a re-write. The firmware's display.cpp is NOT read.
//   node gen_font.mjs [path/to/app.js] > font.h
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(process.argv[2] || resolve(here, 'app.js'), 'utf8');

function extractBlock(startToken) {
  const at = src.indexOf(startToken);
  if (at < 0) throw new Error(`app.js: '${startToken}' not found`);
  const open = src.indexOf('{', at);
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) return src.slice(at, i + 1);
  }
  throw new Error(`app.js: unbalanced '${startToken}'`);
}

const fonts = new Function(`${extractBlock('const fonts =')}; return fonts;`)();
const drawMatrixSrc = extractBlock('function drawMatrix()');
const LIT = /#d5a262/i, DARK = /#242424/i;

// Runs app.js drawMatrix() for one text (a screen message) or one frequency.
function paint({ message = '', frequencyHz = 0 }) {
  const width = 320, pitch = width / 32;
  const ctx = {
    calls: [], cur: null, fillStyle: '',
    scale() {}, beginPath() { this.cur = null; }, arc(x, y) { this.cur = [x, y]; },
    fill() { this.calls.push([this.cur[0], this.cur[1], this.fillStyle]); },
  };
  const canvas = { clientWidth: width, width: 0, height: 0, getContext: () => ctx, setAttribute() {} };
  const $ = sel => (sel === '#matrix' ? canvas : { style: {} });
  const run = new Function('$', 'state', 'screenMessage', 'fonts', 'devicePixelRatio',
    `${drawMatrixSrc}\ndrawMatrix();`);
  run($, { parameters: { frequencyHz } }, message, fonts, 1);
  const cols = new Array(32).fill(0);
  if (ctx.calls.length !== 256) throw new Error(`drawMatrix painted ${ctx.calls.length} dots, expected 32x8`);
  for (const [cx, cy, style] of ctx.calls) {
    const x = Math.round(cx / pitch - 0.5), y = Math.round(cy / pitch - 0.5);
    if (LIT.test(style)) cols[x] |= 1 << y;
    else if (!DARK.test(style)) throw new Error(`unexpected dot colour ${style}`);
  }
  return cols;
}

const glyphs = Object.entries(fonts).map(([ch, rows]) => {
  const w = rows[0].length, cols = [];
  if (rows.length !== 7 || rows.some(r => r.length !== w)) throw new Error(`glyph '${ch}' is not ${w}x7`);
  for (let x = 0; x < w; x++) {
    let c = 0;
    rows.forEach((row, y) => { if (row[x] === '1') c |= 1 << y; });
    cols.push(c);
  }
  return { ch, w, cols };
});

// Every text the CP-100 firmware is meant to show (task list + Rev08), the
// frequency format, and each glyph alone. Texts with characters the app.js
// font lacks (C in CP100, X in MAX, B in BATAL) are rendered too, flagged
// allGlyphs=false: app.js would draw those characters as blanks.
const messages = ['CP100', 'SAVED', 'RAM', 'ERR', 'SAVE', 'SINE', 'SAW', 'TRI', 'ODD', 'EVEN', 'O+E',
  'F 000', 'F 018', 'F 040', 'F 100', 'L 000', 'L 035', 'L 040', 'L 100', 'RUN', 'SERV', 'MUTE', 'TEST',
  '0.1', '1', 'MIN', 'MAX', 'BATAL', 'HELLO', 'P100',
  ...glyphs.map(g => g.ch).filter(c => c !== ' ')];
const frequencies = [20, 25, 30, 128.5, 150, 155, 196, 200, 220, 256, 300, 333.3, 384, 1500, 1999.9, 2000];

const esc = s => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const hex = a => a.map(v => '0x' + v.toString(16).padStart(2, '0').toUpperCase()).join(', ');
const out = [
  '// Generated by gen_font.mjs from simulator/dist/app.js (fonts, drawMatrix); do not edit.',
  '// Columns: bit 0 = top row, x = 0 = leftmost column.',
  '#pragma once',
  '#include <stdint.h>',
  'struct AppGlyph { char c; int width; uint8_t cols[5]; };',
  'static const AppGlyph kAppFont[] = {',
  ...glyphs.map(g => `  {'${g.ch === "'" ? "\\'" : g.ch}', ${g.w}, {${hex(g.cols)}}},`),
  '};',
  '// allGlyphs: every character exists in the app.js font (otherwise app.js draws it as a space).',
  'struct AppRender { const char* text; bool frequency; bool allGlyphs; uint8_t cols[32]; };',
  'static const AppRender kAppRenders[] = {',
];
for (const m of messages) {
  const all = [...m].every(c => c in fonts);
  out.push(`  {"${esc(m)}", false, ${all}, {${hex(paint({ message: m }))}}},`);
}
for (const f of frequencies) out.push(`  {"${f.toFixed(1)}", true, true, {${hex(paint({ frequencyHz: f }))}}},`);
out.push('};');
console.log(out.join('\n'));
