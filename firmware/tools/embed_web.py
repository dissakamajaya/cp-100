"""Embed the offline service UI; deterministic gzip, no filesystem upload needed."""
from pathlib import Path
import gzip
root = Path(__file__).resolve().parents[1]
lines = ['// Generated by tools/embed_web.py; edit firmware/web instead.', '#pragma once', '#include <stdint.h>']
for name, symbol in [('index.html', 'index'), ('app.js', 'app'), ('style.css', 'style')]:
    data = gzip.compress((root / 'web' / name).read_bytes(), mtime=0)
    lines.append(f'static const uint8_t kWeb_{symbol}[] PROGMEM = {{')
    lines.extend('  ' + ','.join(str(x) for x in data[i:i+24]) + ',' for i in range(0, len(data), 24))
    lines.append('};')
target = root / 'src/web_assets.h'
text = '\n'.join(lines) + '\n'
if not target.exists() or target.read_text() != text:
    target.write_text(text)
