// Writes src/calibration_table.h from the simulator's calibrationFor(), so the
// device uses exactly the simulator's loudness calibration without computing
// it at run time (4096 points per entry is ~15 ms on the ESP32-S3).
// Usage: node tools/gen_calibration.mjs ../simulator/dist/dsp.js > src/calibration_table.h
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const { calibrationFor } = await import(pathToFileURL(resolve(process.argv[2])).href);
const waves = ['sine', 'sawtooth', 'triangle'];      // Wave::Sine, Saw, Triangle
const harmonics = ['odd', 'even', 'both'];            // Harmonics::Odd, Even, Both
const f = x => (Object.is(x, -0) || Math.abs(x) < 1e-30 ? 0 : x).toPrecision(9) + 'f';
const lines = [
  '// Generated by tools/gen_calibration.mjs from simulator/dist/dsp.js calibrationFor().',
  '// Do not edit by hand. Index: [wave][harmonics][foldPct * 10, 0..1000] -> {mean, gain}.',
  '#pragma once',
  '',
  'static const Calibration kCalibrationTable[3][3][1001] = {',
];
for (const w of waves) {
  lines.push('  {');
  for (const h of harmonics) {
    const row = [];
    for (let fold = 0; fold <= 1000; fold++) {
      const c = calibrationFor(w, fold / 10, h);
      row.push(`{${f(c.mean)}, ${f(c.gain)}}`);
    }
    lines.push(`    {  // ${w} ${h}`);
    for (let i = 0; i < row.length; i += 4) lines.push('      ' + row.slice(i, i + 4).join(', ') + ',');
    lines.push('    },');
  }
  lines.push('  },');
}
lines.push('};', '');
process.stdout.write(lines.join('\n'));
